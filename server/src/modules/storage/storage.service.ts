/**
 * Storage abstraction + hardened local-disk implementation.
 *
 * Design notes:
 *  - Keys are server-generated (`YYYY/MM/<uuid>.<ext>`). The client filename is
 *    never used to build a path; it is only stored as a display label.
 *  - Every key is validated and the resolved absolute path must stay inside the
 *    upload root — this is the path-traversal guard.
 *  - The upload directory lives OUTSIDE anything served statically; bytes are
 *    only ever returned through an authorising route.
 *  - Swapping in S3 means implementing this interface; no caller changes.
 */
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createReadStream, type ReadStream } from 'node:fs';
import { config } from '../../config/env';
import { NotFoundError, ValidationError } from '../../utils/errors';

export interface StoredObject {
  key: string;
  size: number;
}

export interface StorageService {
  readonly kind: string;
  put(buffer: Buffer, extension: string): Promise<StoredObject>;
  getStream(key: string): Promise<ReadStream>;
  getBuffer(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  exists(key: string): Promise<boolean>;
}

/** Only these extensions can ever be produced by the upload pipeline. */
const ALLOWED_EXTENSIONS = new Set(['jpg', 'png', 'webp']);

/** Storage keys are generated by us, so they must match this exact shape. */
const KEY_PATTERN = /^\d{4}\/\d{2}\/[0-9a-f-]{36}\.(jpg|png|webp)$/;

export class LocalDiskStorage implements StorageService {
  readonly kind = 'local-disk';
  private readonly root: string;

  constructor(root: string = config.uploadDir) {
    this.root = path.resolve(root);
  }

  async init(): Promise<void> {
    await fs.mkdir(this.root, { recursive: true, mode: 0o750 });
  }

  /**
   * Resolve a key to an absolute path, refusing anything that escapes the root.
   * Two layers: shape validation, then a normalised prefix check.
   */
  private resolveKey(key: string): string {
    if (typeof key !== 'string' || !KEY_PATTERN.test(key)) {
      throw new ValidationError('Invalid storage key');
    }
    const absolute = path.resolve(this.root, key);
    const rootWithSep = this.root.endsWith(path.sep) ? this.root : this.root + path.sep;
    if (!absolute.startsWith(rootWithSep)) {
      throw new ValidationError('Invalid storage key');
    }
    return absolute;
  }

  async put(buffer: Buffer, extension: string): Promise<StoredObject> {
    const ext = extension.toLowerCase().replace(/^\./, '');
    if (!ALLOWED_EXTENSIONS.has(ext)) {
      throw new ValidationError('Unsupported image format');
    }

    const now = new Date();
    const year = String(now.getUTCFullYear());
    const month = String(now.getUTCMonth() + 1).padStart(2, '0');
    // Date-sharded so no single directory accumulates unbounded entries.
    const key = `${year}/${month}/${crypto.randomUUID()}.${ext}`;
    const absolute = this.resolveKey(key);

    await fs.mkdir(path.dirname(absolute), { recursive: true, mode: 0o750 });
    // 0o640: readable by the app user only. Never executable.
    await fs.writeFile(absolute, buffer, { mode: 0o640, flag: 'wx' });

    return { key, size: buffer.byteLength };
  }

  async getStream(key: string): Promise<ReadStream> {
    const absolute = this.resolveKey(key);
    try {
      await fs.access(absolute);
    } catch {
      throw new NotFoundError('Image');
    }
    return createReadStream(absolute);
  }

  async getBuffer(key: string): Promise<Buffer> {
    const absolute = this.resolveKey(key);
    try {
      return await fs.readFile(absolute);
    } catch {
      throw new NotFoundError('Image');
    }
  }

  async delete(key: string): Promise<void> {
    const absolute = this.resolveKey(key);
    await fs.rm(absolute, { force: true });
  }

  async exists(key: string): Promise<boolean> {
    try {
      await fs.access(this.resolveKey(key));
      return true;
    } catch {
      return false;
    }
  }
}

export const storageService: StorageService = new LocalDiskStorage();

export async function initStorage(): Promise<void> {
  if (storageService instanceof LocalDiskStorage) {
    await storageService.init();
  }
}
